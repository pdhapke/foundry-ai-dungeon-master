import { test } from "node:test";
import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { mkdtempSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
import { SqlitePreparationJobStore, type PreparationJob } from "./index.js";
test("SQLite store imports legacy once, CAS prevents stale writes across connections and reopen preserves revisions", () => {
  const path = join(mkdtempSync(join(tmpdir(), "prep-sqlite-")), "jobs.sqlite");
  const first = new DatabaseSync(path), second = new DatabaseSync(path);
  let legacyReads = 0;
  const legacy = { read: () => { legacyReads++; return { id: "job", revision: 3 } as PreparationJob; } };
  const a = new SqlitePreparationJobStore(first, legacy), b = new SqlitePreparationJobStore(second, legacy);
  assert.equal(a.read("job")?.revision, 3);
  b.write({ id: "job", revision: 4 } as PreparationJob, 3);
  assert.throws(() => a.write({ id: "job", revision: 4 } as PreparationJob, 3), /Concurrent/);
  assert.equal(a.read("job")?.revision, 4); assert.equal(legacyReads, 1);
  assert.throws(() => a.write({ id: "job", revision: 8 } as PreparationJob, 4), /advance/);
  first.close(); second.close();
  const reopened = new DatabaseSync(path), store = new SqlitePreparationJobStore(reopened);
  assert.equal(store.read("job")?.revision, 4);
  store.write({ id: "new", revision: 1 } as PreparationJob, null);
  assert.throws(() => store.write({ id: "new", revision: 1 } as PreparationJob, null), /Concurrent/);
  reopened.close();
});
test("rolled-back interrupted SQLite transaction leaves resumable previous version", () => {
  const db = new DatabaseSync(":memory:"), store = new SqlitePreparationJobStore(db);
  store.write({ id: "job", revision: 1 } as PreparationJob, null);
  db.exec("BEGIN IMMEDIATE");
  db.prepare("UPDATE preparation_jobs SET revision=2,job_json=? WHERE id='job'").run(JSON.stringify({ id: "job", revision: 2 }));
  db.exec("ROLLBACK");
  assert.equal(store.read("job")?.revision, 1);
  store.write({ id: "job", revision: 2 } as PreparationJob, 1);
  assert.equal(store.read("job")?.revision, 2); db.close();
});
test("process exit with an uncommitted write recovers on reopen without filesystem claim cleanup", () => {
  const path = join(mkdtempSync(join(tmpdir(), "prep-sqlite-exit-")), "jobs.sqlite");
  const db = new DatabaseSync(path), before = new SqlitePreparationJobStore(db);
  before.write({ id: "job", revision: 1 } as PreparationJob, null); db.close();
  const script = `import {DatabaseSync} from 'node:sqlite'; const db=new DatabaseSync(${JSON.stringify(path)});
    db.exec('BEGIN IMMEDIATE'); db.prepare("UPDATE preparation_jobs SET revision=2,job_json=? WHERE id='job'").run(JSON.stringify({id:'job',revision:2})); process.exit(0);`;
  const child = spawnSync(process.execPath, ["--input-type=module", "-e", script], { timeout: 5000, encoding: "utf8" });
  assert.equal(child.status, 0, child.stderr);
  const reopened = new DatabaseSync(path), recovered = new SqlitePreparationJobStore(reopened);
  assert.equal(recovered.read("job")?.revision, 1);
  recovered.write({ id: "job", revision: 2 } as PreparationJob, 1);
  assert.equal(recovered.read("job")?.revision, 2); reopened.close();
});
